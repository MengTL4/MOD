using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ShimGen;

/// <summary>
/// Mechanical source fixes for behaviour that differs between the game's Mono runtime and .NET 10.
/// Rewritten copies go to src/Lonestar.Game/Rewritten and the originals are excluded from the
/// build via Rewritten.props; decompiled/ itself is never modified.
///
/// Rules:
///  - string.GetHashCode() → Lonestar.Rng.MonoHash.Hash(s): .NET randomizes string hashes per
///    process, while the game seeds its RNG streams from Mono's fixed hash.
///  - Task.Delay(...) → UnityEngine.HeadlessAsync.Delay(...): the game awaits real-time delays in a
///    few async void UI effects; in Unity the continuation comes back on the main thread, headless
///    it would run on the thread pool (a data race with the frame loop). The shim completes the
///    delay on the virtual clock instead.
/// </summary>
internal sealed class Rewriter : CSharpSyntaxRewriter
{
    private readonly SemanticModel model;

    public int Rewrites { get; private set; }

    private Rewriter(SemanticModel model)
    {
        this.model = model;
    }

    public static void Run(CSharpCompilation compilation, string decompiledRoot, string gameProjectDir)
    {
        string outDir = Path.Combine(gameProjectDir, "Rewritten");
        if (Directory.Exists(outDir))
        {
            Directory.Delete(outDir, recursive: true);
        }
        var removed = new List<string>();
        int total = 0;
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            var rewriter = new Rewriter(compilation.GetSemanticModel(tree));
            SyntaxNode root = rewriter.Visit(tree.GetRoot());
            if (rewriter.Rewrites == 0)
            {
                continue;
            }
            total += rewriter.Rewrites;
            string target = Path.Combine(outDir, tree.FilePath);
            Directory.CreateDirectory(Path.GetDirectoryName(target));
            File.WriteAllText(target, "// <auto-generated> rewritten by tools/ShimGen from decompiled/" + tree.FilePath.Replace('\\', '/') + "\n" + root.ToFullString());
            removed.Add(tree.FilePath);
            Console.WriteLine($"  rewrote {tree.FilePath} ({rewriter.Rewrites})");
        }

        var props = new StringBuilder();
        props.AppendLine("<Project>");
        props.AppendLine("  <!-- <auto-generated> by tools/ShimGen rewrite: originals replaced by Rewritten/ copies. -->");
        props.AppendLine("  <ItemGroup>");
        foreach (string rel in removed)
        {
            props.AppendLine($"    <Compile Remove=\"..\\..\\decompiled\\{rel}\" />");
        }
        props.AppendLine("    <Compile Include=\"Rewritten\\**\\*.cs\" />");
        props.AppendLine("  </ItemGroup>");
        props.AppendLine("</Project>");
        File.WriteAllText(Path.Combine(gameProjectDir, "Rewritten.props"), props.ToString());
        Console.WriteLine($"Rewrote {total} sites in {removed.Count} files");
    }

    public override SyntaxNode VisitInvocationExpression(InvocationExpressionSyntax node)
    {
        var visited = (InvocationExpressionSyntax)base.VisitInvocationExpression(node);
        if (node.Expression is MemberAccessExpressionSyntax access
            && node.ArgumentList.Arguments.Count == 0
            && model.GetSymbolInfo(node).Symbol is IMethodSymbol { Name: "GetHashCode" } method
            && method.ContainingType.SpecialType == SpecialType.System_String)
        {
            Rewrites++;
            var receiver = ((MemberAccessExpressionSyntax)visited.Expression).Expression;
            return SyntaxFactory.ParseExpression($"global::Lonestar.Rng.MonoHash.Hash({receiver.ToFullString().Trim()})")
                .WithTriviaFrom(node);
        }
        if (node.Expression is MemberAccessExpressionSyntax
            && model.GetSymbolInfo(node).Symbol is IMethodSymbol { Name: "Delay", IsStatic: true } delay
            && delay.ContainingType.ToDisplayString() == "System.Threading.Tasks.Task")
        {
            Rewrites++;
            return SyntaxFactory.ParseExpression($"global::UnityEngine.HeadlessAsync.Delay{visited.ArgumentList.ToFullString().Trim()}")
                .WithTriviaFrom(node);
        }
        return visited;
    }
}
