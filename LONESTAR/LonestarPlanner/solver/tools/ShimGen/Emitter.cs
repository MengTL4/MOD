using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace ShimGen;

/// <summary>
/// Emits C# stubs for the collected external API. Every type is emitted <c>partial</c> so a
/// hand-written part (see <see cref="ManualParts"/>) can supply real behaviour:
///  - members a manual part declares are skipped here;
///  - leftover members of manually implemented types throw, so a gap is loud, not silently wrong;
///  - members of purely generated types return null objects (see Shim.Ret) so UI code is inert.
/// </summary>
internal sealed class Emitter
{
    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.UseSpecialTypes | SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

    private static readonly Dictionary<string, string> Operators = new()
    {
        ["op_Addition"] = "+", ["op_Subtraction"] = "-", ["op_Multiply"] = "*", ["op_Division"] = "/",
        ["op_Modulus"] = "%", ["op_Equality"] = "==", ["op_Inequality"] = "!=", ["op_LessThan"] = "<",
        ["op_GreaterThan"] = ">", ["op_LessThanOrEqual"] = "<=", ["op_GreaterThanOrEqual"] = ">=",
        ["op_UnaryNegation"] = "-", ["op_UnaryPlus"] = "+", ["op_LogicalNot"] = "!", ["op_True"] = "true",
        ["op_False"] = "false", ["op_BitwiseAnd"] = "&", ["op_BitwiseOr"] = "|", ["op_ExclusiveOr"] = "^",
        ["op_OnesComplement"] = "~", ["op_Increment"] = "++", ["op_Decrement"] = "--",
        ["op_LeftShift"] = "<<", ["op_RightShift"] = ">>",
    };

    private static readonly Dictionary<string, string> OperatorPartner = new()
    {
        ["op_Equality"] = "op_Inequality", ["op_Inequality"] = "op_Equality",
        ["op_LessThan"] = "op_GreaterThan", ["op_GreaterThan"] = "op_LessThan",
        ["op_LessThanOrEqual"] = "op_GreaterThanOrEqual", ["op_GreaterThanOrEqual"] = "op_LessThanOrEqual",
        ["op_True"] = "op_False", ["op_False"] = "op_True",
    };

    private readonly UsageCollector usage;
    private readonly ManualParts manual;
    private readonly StringBuilder sb = new();
    private int indent;

    public int EmittedMembers { get; private set; }

    public int ThrowingMembers { get; private set; }

    public Emitter(UsageCollector usage, ManualParts manual)
    {
        this.usage = usage;
        this.manual = manual;
        AddOperatorPartners();
    }

    private void AddOperatorPartners()
    {
        foreach (IMethodSymbol m in usage.Members.OfType<IMethodSymbol>().ToList())
        {
            if (m.MethodKind == MethodKind.UserDefinedOperator && OperatorPartner.TryGetValue(m.Name, out string partner))
            {
                foreach (IMethodSymbol p in m.ContainingType.GetMembers(partner).OfType<IMethodSymbol>())
                {
                    usage.AddSymbol(p);
                }
            }
        }
    }

    public string Emit()
    {
        Line("// <auto-generated> by tools/ShimGen from the game's real assemblies. Do not edit.");
        Line("#pragma warning disable CS0067, CS0108, CS0114, CS0169, CS0414, CS0649, CS0660, CS0661, CS0809, CS1998");
        Line();
        var topLevel = usage.Types.Where(t => t.ContainingType == null)
            .GroupBy(t => t.ContainingNamespace.IsGlobalNamespace ? "" : t.ContainingNamespace.ToDisplayString())
            .OrderBy(g => g.Key, StringComparer.Ordinal);
        foreach (var ns in topLevel)
        {
            if (ns.Key.Length > 0)
            {
                Line($"namespace {ns.Key}");
                Line("{");
                indent++;
            }
            foreach (INamedTypeSymbol t in ns.OrderBy(t => t.MetadataName, StringComparer.Ordinal))
            {
                EmitType(t);
            }
            if (ns.Key.Length > 0)
            {
                indent--;
                Line("}");
            }
            Line();
        }
        return sb.ToString();
    }

    // ---- types ------------------------------------------------------------------------------

    private void EmitType(INamedTypeSymbol t)
    {
        string fullName = FullName(t);
        bool isManual = manual.HasType(fullName);
        bool leftoversThrow = isManual && !manual.IsLenient(fullName);
        const string access = "public";

        if (t.TypeKind == TypeKind.Enum)
        {
            if (isManual)
            {
                return;
            }
            if (t.GetAttributes().Any(a => a.AttributeClass?.Name == "FlagsAttribute"))
            {
                Line("[global::System.Flags]");
            }
            Line($"{access} enum {Escape(t.Name)} : {Display(t.EnumUnderlyingType)}");
            Line("{");
            indent++;
            foreach (IFieldSymbol f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
            {
                Line($"{Escape(f.Name)} = {Literal(f.ConstantValue, t.EnumUnderlyingType)},");
            }
            indent--;
            Line("}");
            return;
        }

        if (t.TypeKind == TypeKind.Delegate)
        {
            if (isManual)
            {
                return;
            }
            IMethodSymbol inv = t.DelegateInvokeMethod;
            Line($"{access} delegate {Display(inv.ReturnType)} {Escape(t.Name)}{TypeParams(t.TypeParameters)}({Params(inv.Parameters)}){Constraints(t.TypeParameters)};");
            return;
        }

        string kind = t.TypeKind switch
        {
            TypeKind.Interface => "interface",
            TypeKind.Struct => "struct",
            _ => "class",
        };
        var modifiers = new List<string> { access };
        if (t.IsStatic)
        {
            modifiers.Add("static");
        }
        else if (t.IsAbstract && t.TypeKind == TypeKind.Class)
        {
            modifiers.Add("abstract");
        }
        modifiers.Add("partial");

        var bases = new List<string>();
        if (t.TypeKind == TypeKind.Class && t.BaseType != null && t.BaseType.SpecialType != SpecialType.System_Object)
        {
            if (usage.IsExternal(t.BaseType) || UsageCollector.IsBcl(t.BaseType.ContainingAssembly))
            {
                bases.Add(Display(t.BaseType));
            }
        }
        foreach (INamedTypeSymbol i in t.Interfaces.Where(i => usage.IsExternal(i)))
        {
            bases.Add(Display(i));
        }
        if (t.IsAttributeType())
        {
            Line("[global::System.AttributeUsage(global::System.AttributeTargets.All, AllowMultiple = true, Inherited = true)]");
        }
        string baseList = bases.Count > 0 ? " : " + string.Join(", ", bases) : "";
        Line($"{string.Join(" ", modifiers)} {kind} {Escape(t.Name)}{TypeParams(t.TypeParameters)}{baseList}{Constraints(t.TypeParameters)}");
        Line("{");
        indent++;

        if (t.TypeKind == TypeKind.Class && !t.IsStatic && !manual.HasMember(fullName, ".ctor", 0)
            && !t.InstanceConstructors.Any(c => c.Parameters.Length == 0 && usage.Members.Contains(c)))
        {
            // Every class gets a parameterless constructor so derived game classes and Shim.Ret work.
            Line($"public {Escape(t.Name)}() {{ }}");
        }

        var members = usage.Members.Where(m => SymbolEqualityComparer.Default.Equals(m.ContainingType, t))
            .OrderBy(m => m.Kind).ThenBy(m => m.Name, StringComparer.Ordinal).ThenBy(m => m.ToDisplayString(), StringComparer.Ordinal);
        foreach (ISymbol m in members)
        {
            EmitMember(t, m, leftoversThrow);
        }
        if (t.TypeKind is TypeKind.Class or TypeKind.Struct)
        {
            EmitExplicitInterfaceImpls(t);
        }
        foreach (INamedTypeSymbol nested in usage.Types.Where(n => SymbolEqualityComparer.Default.Equals(n.ContainingType, t)).OrderBy(n => n.MetadataName, StringComparer.Ordinal))
        {
            EmitType(nested);
        }
        indent--;
        Line("}");
    }

    /// <summary>
    /// Generated interfaces only declare the members the game uses, so a generated class listing
    /// such an interface implements exactly those, explicitly, with inert bodies.
    /// </summary>
    private void EmitExplicitInterfaceImpls(INamedTypeSymbol t)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (INamedTypeSymbol direct in t.Interfaces.Where(i => usage.IsExternal(i)))
        {
            foreach (INamedTypeSymbol ix in new[] { direct }.Concat(direct.AllInterfaces).Where(i => usage.IsExternal(i)))
            {
                if (!seen.Add(ix))
                {
                    continue;
                }
                string iface = Display(ix);
                foreach (ISymbol m in ix.GetMembers().Where(m => usage.Members.Contains(m.OriginalDefinition)))
                {
                    switch (m)
                    {
                        case IMethodSymbol { MethodKind: MethodKind.Ordinary } im:
                        {
                            string outs = string.Concat(im.Parameters.Where(p => p.RefKind == RefKind.Out).Select(p => $"{Escape(p.Name)} = default; "));
                            string ps = Params(im.Parameters).Replace("params ", "");
                            string body = im.ReturnsVoid ? $"{{ {outs}}}" : $"{{ {outs}return global::UnityEngine.Shim.Ret<{Display(im.ReturnType)}>(); }}";
                            Line($"{Display(im.ReturnType)} {iface}.{Escape(im.Name)}{TypeParams(im.TypeParameters)}({StripDefaults(ps)}) {body}");
                            break;
                        }
                        case IPropertySymbol ip:
                        {
                            string head = ip.IsIndexer ? $"{iface}.this[{StripDefaults(Params(ip.Parameters))}]" : $"{iface}.{Escape(ip.Name)}";
                            string get = ip.GetMethod != null ? $"get => global::UnityEngine.Shim.Ret<{Display(ip.Type)}>(); " : "";
                            string set = ip.SetMethod != null ? "set { } " : "";
                            Line($"{Display(ip.Type)} {head} {{ {get}{set}}}");
                            break;
                        }
                        case IEventSymbol ie:
                            Line($"event {Display(ie.Type)} {iface}.{Escape(ie.Name)} {{ add {{ }} remove {{ }} }}");
                            break;
                    }
                    EmittedMembers++;
                }
            }
        }
    }

    private static string StripDefaults(string ps) =>
        System.Text.RegularExpressions.Regex.Replace(ps, @" = [^,]+(?=,|$)", "");

    // ---- members ----------------------------------------------------------------------------

    private void EmitMember(INamedTypeSymbol owner, ISymbol m, bool ownerIsManual)
    {
        string ownerName = FullName(owner);
        bool isInterface = owner.TypeKind == TypeKind.Interface;
        switch (m)
        {
            case IFieldSymbol f:
            {
                if (manual.HasMember(ownerName, f.Name, -1))
                {
                    return;
                }
                string mods = Access(f) + (f.IsConst ? " const" : f.IsStatic ? " static" : "");
                string init = f.IsConst ? " = " + Literal(f.ConstantValue, f.Type)
                    : f.IsStatic && f.IsReadOnly ? $" = global::UnityEngine.Shim.Ret<{Display(f.Type)}>()"
                    : !f.IsStatic && IsSerializedByValue(f.Type) ? $" = new {Display(f.Type)}()" : "";
                if (f.IsStatic && f.IsReadOnly && !f.IsConst)
                {
                    mods += " readonly";
                }
                Line($"{mods} {Display(f.Type)} {Escape(f.Name)}{init};");
                Count(false);
                return;
            }
            case IPropertySymbol p:
            {
                string name = p.IsIndexer ? "this" : p.Name;
                if (manual.HasMember(ownerName, name, p.Parameters.Length))
                {
                    return;
                }
                bool throws = ownerIsManual;
                string head = p.IsIndexer ? $"this[{Params(p.Parameters)}]" : Escape(p.Name);
                string get = p.GetMethod != null && Visible(p.GetMethod) ? (isInterface ? "get;" : $"get => {Ret(p.Type, throws, ownerName, name)};") : "";
                string set = p.SetMethod != null && Visible(p.SetMethod) ? (isInterface ? "set;" : (throws ? $"set => {Throw(ownerName, name)};" : "set { }")) : "";
                if (get.Length == 0 && set.Length == 0)
                {
                    get = isInterface ? "get;" : $"get => {Ret(p.Type, throws, ownerName, name)};";
                }
                Line($"{MemberModifiers(p, isInterface)}{Display(p.Type)} {head} {{ {get} {set} }}".Replace("  ", " "));
                Count(throws);
                return;
            }
            case IEventSymbol e:
            {
                if (manual.HasMember(ownerName, e.Name, -1))
                {
                    return;
                }
                Line($"{MemberModifiers(e, isInterface)}event {Display(e.Type)} {Escape(e.Name)};");
                Count(false);
                return;
            }
            case IMethodSymbol method:
                EmitMethod(owner, method, ownerIsManual, isInterface);
                return;
        }
    }

    private void EmitMethod(INamedTypeSymbol owner, IMethodSymbol m, bool ownerIsManual, bool isInterface)
    {
        string ownerName = FullName(owner);
        bool throws = ownerIsManual;
        string ps = Params(m.Parameters, m.IsExtensionMethod);
        string outs = string.Concat(m.Parameters.Where(p => p.RefKind == RefKind.Out).Select(p => $"{Escape(p.Name)} = default; "));
        switch (m.MethodKind)
        {
            case MethodKind.Constructor:
            {
                if (owner.TypeKind == TypeKind.Struct && m.Parameters.Length == 0)
                {
                    return;
                }
                if (manual.HasMember(ownerName, ".ctor", m.Parameters.Length))
                {
                    return;
                }
                string body = throws ? $"{{ {outs}{Throw(ownerName, ".ctor")}; }}" : $"{{ {outs}}}";
                string chain = owner.TypeKind == TypeKind.Struct ? " : this()" : "";
                Line($"{Access(m)} {Escape(owner.Name)}({ps}){chain} {body}");
                Count(throws);
                return;
            }
            case MethodKind.StaticConstructor:
            case MethodKind.Destructor:
                return;
            case MethodKind.UserDefinedOperator:
            case MethodKind.Conversion:
            {
                if (manual.HasOperators(ownerName))
                {
                    return;
                }
                string head = m.MethodKind == MethodKind.Conversion
                    ? $"{(m.Name == "op_Implicit" ? "implicit" : "explicit")} operator {Display(m.ReturnType)}"
                    : $"{Display(m.ReturnType)} operator {Operators[m.Name]}";
                Line($"public static {head}({ps}) => {Ret(m.ReturnType, throws, ownerName, m.Name)};");
                Count(throws);
                return;
            }
            case MethodKind.Ordinary:
            case MethodKind.DelegateInvoke:
                break;
            default:
                return;
        }

        if (manual.HasMember(ownerName, m.Name, m.Parameters.Length))
        {
            return;
        }
        string sig = $"{Display(m.ReturnType)} {Escape(m.Name)}{TypeParams(m.TypeParameters)}({ps}){Constraints(m.TypeParameters, forOverride: false)}";
        if (isInterface)
        {
            Line($"{sig};");
            Count(false);
            return;
        }
        string mods = MemberModifiers(m, false);
        if (m.ReturnsVoid)
        {
            Line($"{mods}{sig} {{ {outs}{(throws ? Throw(ownerName, m.Name) + ";" : "")} }}".Replace("  ", " "));
            Count(throws);
            return;
        }
        // Fluent setters (SetEase, SetUpdate, ...) hand back their receiver, even on manual types.
        if (m.IsExtensionMethod && IsSameOrBase(m.ReturnType, m.Parameters[0].Type))
        {
            Line($"{mods}{sig} {{ {outs}return {Escape(m.Parameters[0].Name)}; }}");
            Count(false);
            return;
        }
        if (!throws && IsTween(m.ReturnType))
        {
            Line($"{mods}{sig} {{ {outs}return {TweenFactoryCall(m)}; }}");
            Count(false);
            return;
        }
        Line(throws
            ? $"{mods}{sig} {{ {outs}{Throw(ownerName, m.Name)}; }}"
            : $"{mods}{sig} {{ {outs}return {Ret(m.ReturnType, false, ownerName, m.Name)}; }}");
        Count(throws);
    }

    /// <summary>A live tween with the call's duration, so OnComplete-style callbacks fire on time.</summary>
    private static string TweenFactoryCall(IMethodSymbol m)
    {
        ITypeSymbol ret = m.ReturnType;
        string type = ret.IsAbstract ? "global::DG.Tweening.ShimTweener" : Display(ret);
        IParameterSymbol durationParam = m.Parameters.FirstOrDefault(p => p.Name == "duration" && p.Type.SpecialType == SpecialType.System_Single);
        string duration = durationParam != null ? Escape(durationParam.Name) : "0f";
        string target = m.IsExtensionMethod ? Escape(m.Parameters[0].Name) : "null";
        string call = $"global::DG.Tweening.TweenFactory.Make<{type}>({duration}, {target})";
        return ret.IsAbstract ? $"({Display(ret)}){call}" : call;
    }

    private static bool IsTween(ITypeSymbol t)
    {
        for (ITypeSymbol b = t; b != null; b = b.BaseType)
        {
            if (b.ToDisplayString() == "DG.Tweening.Tween")
            {
                return true;
            }
        }
        return false;
    }

    private static bool IsSameOrBase(ITypeSymbol ret, ITypeSymbol param)
    {
        if (ret is ITypeParameterSymbol || param is ITypeParameterSymbol)
        {
            return SymbolEqualityComparer.Default.Equals(ret, param);
        }
        for (ITypeSymbol b = param; b != null; b = b.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(b.OriginalDefinition, ret.OriginalDefinition))
            {
                return true;
            }
        }
        return false;
    }

    /// <summary>
    /// Unity's serializer never leaves fields of serializable classes (UnityEvents, Lists...) null,
    /// so stub fields of such types start with an instance, as they would in the game.
    /// </summary>
    private bool IsSerializedByValue(ITypeSymbol t)
    {
        if (t is not INamedTypeSymbol n || n.TypeKind != TypeKind.Class || n.IsAbstract || n.IsStatic)
        {
            return false;
        }
        if (n.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.List<T>")
        {
            return true;
        }
        for (ITypeSymbol b = n; b != null; b = b.BaseType)
        {
            if (b.ToDisplayString() == "UnityEngine.Object")
            {
                return false;
            }
        }
        return usage.IsExternal(n) && n.TypeKind != TypeKind.Delegate;
    }

    private void Count(bool throws)
    {
        EmittedMembers++;
        if (throws)
        {
            ThrowingMembers++;
        }
    }

    // ---- helpers ----------------------------------------------------------------------------

    private static bool Visible(IMethodSymbol accessor) =>
        accessor.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal;

    private static string Access(ISymbol s) => s.DeclaredAccessibility switch
    {
        Accessibility.Protected or Accessibility.ProtectedOrInternal or Accessibility.ProtectedAndInternal => "protected",
        _ => "public",
    };

    private static string MemberModifiers(ISymbol s, bool isInterface)
    {
        if (isInterface)
        {
            return s.IsStatic ? "static " : "";
        }
        string access = Access(s);
        if (s.IsStatic)
        {
            return access + " static ";
        }
        // Virtuality is kept (abstract becomes virtual) so game overrides bind; sealed/override chains are flattened.
        bool isVirtual = (s.IsVirtual || s.IsAbstract || s.IsOverride) && !s.IsSealed && s.ContainingType.TypeKind == TypeKind.Class;
        return access + (isVirtual ? " virtual " : " ");
    }

    private static string Ret(ITypeSymbol type, bool throws, string owner, string member) =>
        throws ? Throw(owner, member) : $"global::UnityEngine.Shim.Ret<{Display(type)}>()";

    private static string Throw(string owner, string member) =>
        $"throw new global::UnityEngine.ShimNotImplementedException(\"{owner}.{member}\")";

    private static string Params(System.Collections.Immutable.ImmutableArray<IParameterSymbol> ps, bool extension = false)
    {
        var parts = new List<string>();
        for (int i = 0; i < ps.Length; i++)
        {
            IParameterSymbol p = ps[i];
            string mod = p.RefKind switch
            {
                RefKind.Ref => "ref ",
                RefKind.Out => "out ",
                RefKind.In => "in ",
                _ => "",
            };
            if (p.IsParams)
            {
                mod = "params ";
            }
            if (extension && i == 0)
            {
                mod = "this " + mod;
            }
            string def = p.HasExplicitDefaultValue ? " = " + DefaultLiteral(p) : "";
            parts.Add($"{mod}{Display(p.Type)} {Escape(p.Name)}{def}");
        }
        return string.Join(", ", parts);
    }

    private static string DefaultLiteral(IParameterSymbol p)
    {
        object v = p.ExplicitDefaultValue;
        if (v == null)
        {
            return "default";
        }
        return Literal(v, p.Type);
    }

    private static string Literal(object v, ITypeSymbol type)
    {
        if (type.TypeKind == TypeKind.Enum)
        {
            var underlying = ((INamedTypeSymbol)type).EnumUnderlyingType;
            return $"({Display(type)})({Literal(v, underlying)})";
        }
        return v switch
        {
            null => "default",
            string s => SymbolDisplay.FormatLiteral(s, true),
            char c => SymbolDisplay.FormatLiteral(c, true),
            bool b => b ? "true" : "false",
            float f => float.IsPositiveInfinity(f) ? "float.PositiveInfinity" : float.IsNegativeInfinity(f) ? "float.NegativeInfinity"
                : float.IsNaN(f) ? "float.NaN" : f.ToString("R", CultureInfo.InvariantCulture) + "f",
            double d => double.IsPositiveInfinity(d) ? "double.PositiveInfinity" : double.IsNegativeInfinity(d) ? "double.NegativeInfinity"
                : double.IsNaN(d) ? "double.NaN" : d.ToString("R", CultureInfo.InvariantCulture) + "d",
            uint u => u.ToString(CultureInfo.InvariantCulture) + "u",
            long l => l.ToString(CultureInfo.InvariantCulture) + "L",
            ulong ul => ul.ToString(CultureInfo.InvariantCulture) + "UL",
            int i when type.SpecialType is SpecialType.System_Int32 => i.ToString(CultureInfo.InvariantCulture),
            _ => $"unchecked(({Display(type)}){Convert.ToString(v, CultureInfo.InvariantCulture)})",
        };
    }

    private static string TypeParams(System.Collections.Immutable.ImmutableArray<ITypeParameterSymbol> tps)
    {
        if (tps.Length == 0)
        {
            return "";
        }
        return "<" + string.Join(", ", tps.Select(tp => (tp.Variance switch
        {
            VarianceKind.In => "in ",
            VarianceKind.Out => "out ",
            _ => "",
        }) + Escape(tp.Name))) + ">";
    }

    private static string Constraints(System.Collections.Immutable.ImmutableArray<ITypeParameterSymbol> tps, bool forOverride = false)
    {
        var sbc = new StringBuilder();
        foreach (ITypeParameterSymbol tp in tps)
        {
            var parts = new List<string>();
            if (tp.HasUnmanagedTypeConstraint)
            {
                parts.Add("unmanaged");
            }
            else if (tp.HasValueTypeConstraint)
            {
                parts.Add("struct");
            }
            else if (tp.HasReferenceTypeConstraint)
            {
                parts.Add("class");
            }
            parts.AddRange(tp.ConstraintTypes.Select(Display));
            if (tp.HasConstructorConstraint && !tp.HasValueTypeConstraint)
            {
                parts.Add("new()");
            }
            if (parts.Count > 0)
            {
                sbc.Append($" where {Escape(tp.Name)} : {string.Join(", ", parts)}");
            }
        }
        return sbc.ToString();
    }

    public static string Display(ITypeSymbol t) => t.ToDisplayString(TypeFormat);

    public static string FullName(INamedTypeSymbol t)
    {
        string ns = t.ContainingType != null ? FullName(t.ContainingType) : t.ContainingNamespace.IsGlobalNamespace ? "" : t.ContainingNamespace.ToDisplayString();
        return ns.Length == 0 ? t.Name : ns + "." + t.Name;
    }

    private static string Escape(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private void Line(string text = "")
    {
        if (text.Length > 0)
        {
            sb.Append(' ', indent * 4);
        }
        sb.AppendLine(text);
    }
}

internal static class SymbolExtensions
{
    public static bool IsAttributeType(this INamedTypeSymbol t)
    {
        for (INamedTypeSymbol b = t.BaseType; b != null; b = b.BaseType)
        {
            if (b.ToDisplayString() == "System.Attribute")
            {
                return true;
            }
        }
        return false;
    }
}
